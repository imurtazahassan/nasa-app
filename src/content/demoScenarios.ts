function recentDates(daysBack: number, totalDays: number): string[] {
  const out: string[] = [];
  const today = new Date();
  for (let i = -daysBack; i < totalDays - daysBack; i++) {
    const d = new Date(today.getTime() + i * 86400000);
    out.push(d.toISOString().slice(0, 10));
  }
  return out;
}

